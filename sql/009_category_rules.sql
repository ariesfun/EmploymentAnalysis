-- 009_category_rules.sql  岗类词典扩充（治理「未映射」）
--
-- 背景：未映射岗位占 10.8%，其中大量是词典漏词而非真的无法归类：
--   软件研发 / 程序开发 / 研发岗 / AI智能体 / 网络维护员 / 库管 / 调试工 / 导演编导 …
-- 关键设计：**先排除"非软件研发"，再兜底"研发"**。
--   否则「食品研发」「小吃研发师」会被 研发 -> 后端开发 误吞。
--
-- 只插入不存在的 pattern，可重复执行。

INSERT INTO dict_category(pattern, category, priority)
SELECT v.pattern, v.category, v.priority
FROM (VALUES
  -- ① 非软件研发（必须排在最前，否则会被"研发"兜底吞掉）
  (5,  '食品|小吃|营养|饮品|调味|烘焙|面点|面包|饲料|化妆品|配方|家清|洗涤|日化|粮油', '产品研发(非软件)'),
  -- ② 传媒内容
  (6,  '导演|编导|摄像|剪辑|主播|直播|编辑|记者|文案|编剧|短视频|摄影|短剧', '传媒/内容'),
  -- ③ 安全消防（注意：不含"安全"二字，避免抢走"网络安全"）
  (7,  '消防|应急管理|安保|安全员|EHS', '安全/消防'),
  -- ④ AI 补充：智能体 / Agent / 独立 AI 词
  (8,  '智能体|Agent|(?<![A-Za-z])AI(?![A-Za-z])', '算法/AI'),
  -- ⑤ 数据补充
  (12, '可视化|报表|指标|统计|(?<![A-Za-z])BI(?![A-Za-z])', '数据'),
  -- ⑥ 运维补充
  (62, '网络维护|网管|IT支持|系统维护|弱电', '运维/SRE'),
  -- ⑦ 硬件补充
  (82, '电路设计|电源工程|硬件工程|结构工程|电气', '嵌入式/硬件'),
  -- ⑧ 材料/化工/电池研发（同属非软件）
  (85, '材料|电池|化工|涂料|塑料|橡胶|医药研发', '产品研发(非软件)'),
  -- ⑨ 软件研发兜底（"研发"泛词之前）
  (95, '软件研发|程序开发|原生开发|研发岗|研发序列|研发专家|存储引擎|服务器开发|系统开发|应用开发|客户端|桌面|上位机|软件设计|C语言', '后端开发'),
  -- ⑩ 泛研发兜底
  (97, '研发|技术员', '后端开发'),
  -- ⑪ 机械补充
  (125, '零部件|汽配|汽车工程', '机械/制造'),
  -- ⑫ 物流补充
  (142, '库管|库房|物料|打包|分拣', '物流/仓储'),
  -- ⑬ 普工补充
  (162, '调试工|品检|质量检验|质检员|检验员|钳工', '普工/操作'),
  -- ⑭ 职能补充
  (185, '带岗|招聘专员|猎头|管培生|领班|中层管理|董事会秘书', '职能'),
  -- ⑮ 销售/市场补充
  (195, '物业|选址|门店|督导|催收|(?<![A-Za-z])BD(?![A-Za-z])', '销售/市场'),
  -- ⑯ 第二轮：常见漏词
  (96,  'qt开发|服务器程序|信息技术岗', '后端开发'),
  (143, '供应链', '物流/仓储'),
  (163, '检验', '普工/操作'),
  (186, '文秘', '职能'),
  (200, '网络营销|售前|选品|店员|业务经理|分公司负责人|联合创始人', '销售/市场')
) AS v(priority, pattern, category)
WHERE NOT EXISTS (SELECT 1 FROM dict_category d WHERE d.pattern = v.pattern);

